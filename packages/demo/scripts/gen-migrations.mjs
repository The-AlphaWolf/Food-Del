// Embed the SQL migrations (in journal order) as a TypeScript module, so the browser bundle can
// create the schema without a filesystem. Output is generated; don't edit it.
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../../db/migrations/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({
    tag: e.tag,
    statements: readFileSync(new URL(`${e.tag}.sql`, dir), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));
writeFileSync(
  new URL("../src/migrations.gen.ts", import.meta.url),
  `// Generated by scripts/gen-migrations.mjs from packages/db/migrations. Do not edit.\nexport const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 1)};\n`,
);
console.log(`Embedded ${migrations.length} migrations.`);
